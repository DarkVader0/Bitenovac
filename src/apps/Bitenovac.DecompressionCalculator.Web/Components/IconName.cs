namespace Bitenovac.DecompressionCalculator.Web.Components;

/// <summary>
/// Specifies an action icon, drawn the same wherever the action appears.
/// </summary>
public enum IconName
{
    /// <summary>
    /// Adds something: a plan, a dive, a level or a cylinder.
    /// </summary>
    Add,

    /// <summary>
    /// Removes something: a plan, a dive, a level or a cylinder.
    /// </summary>
    Remove,

    /// <summary>
    /// Makes a copy of a plan.
    /// </summary>
    Copy
}
