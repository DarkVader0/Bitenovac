-- One typed, empty table per telemetry record. Compaction casts every raw JSON line to these
-- types, so a column that happens to be null all day keeps its type.

CREATE TABLE schema_build (
    SchemaVersion INTEGER,
    BuildId VARCHAR,
    Queue VARCHAR,
    Pool VARCHAR,
    Repository VARCHAR,
    Ref VARCHAR,
    Sha VARCHAR,
    PullRequest INTEGER,
    Result VARCHAR,
    CreatedTime TIMESTAMPTZ,
    StartTime TIMESTAMPTZ,
    EndTime TIMESTAMPTZ,
    QueueTimeMS BIGINT,
    PreparationTimeMS BIGINT,
    E2ETimeMS BIGINT,
    Jobs INTEGER,
    Stages INTEGER,
    StageTimeMS BIGINT,
    CpuTimeMS BIGINT,
    AllocatedCpuMS BIGINT,
    CpuUtilization DOUBLE,
    PeakMemoryBytes BIGINT,
    MemoryUtilization DOUBLE,
    HostCpuUtilization DOUBLE,
    HostMemoryUtilization DOUBLE,
    MachinesUsed INTEGER,
    CacheHits INTEGER,
    CacheMisses INTEGER,
    TestsFailed INTEGER,
    FirstError VARCHAR,
    LogsPath VARCHAR,
    DropVersion VARCHAR
);

