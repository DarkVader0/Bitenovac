namespace Bitenovac.DecompressionCalculator.Web.Components;

/// <summary>
/// Specifies an icon, drawn the same wherever it appears.
/// </summary>
public enum IconName
{
    /// <summary>
    /// Adds something: a plan, a dive, a level or a cylinder.
    /// </summary>
    Add,

    /// <summary>
    /// Removes something: a plan, a dive, a level or a cylinder.
    /// </summary>
    Remove,

    /// <summary>
    /// Makes a copy of a plan.
    /// </summary>
    Copy,

    /// <summary>
    /// Opens the list of saved plans.
    /// </summary>
    Plans,

    /// <summary>
    /// Shares the plan.
    /// </summary>
    Share,

    /// <summary>
    /// Opens the settings.
    /// </summary>
    Settings,

    /// <summary>
    /// Saves a file to the device.
    /// </summary>
    Download,

    /// <summary>
    /// Prints.
    /// </summary>
    Print,

    /// <summary>
    /// Closes a sheet or a panel.
    /// </summary>
    Close,

    /// <summary>
    /// Grips an item to drag it to another place in a list.
    /// </summary>
    Grip,

    /// <summary>
    /// Opens the gas calculators.
    /// </summary>
    Calculator,

    /// <summary>
    /// Installs the app.
    /// </summary>
    Install,

    /// <summary>
    /// Reloads the app onto its new version.
    /// </summary>
    Reload,

    /// <summary>
    /// A descent.
    /// </summary>
    Descent,

    /// <summary>
    /// Time at a level.
    /// </summary>
    Level,

    /// <summary>
    /// An ascent.
    /// </summary>
    Ascent,

    /// <summary>
    /// A stop.
    /// </summary>
    Stop,

    /// <summary>
    /// A change of gas.
    /// </summary>
    GasSwitch
}
